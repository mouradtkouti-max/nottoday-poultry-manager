    fun lookup(key: String, lang: AppLanguage): String? {
        sharedMultiLangKeys[key]?.get(lang.code)?.let { return it }
        return when (lang) {
            AppLanguage.TR -> trDict[key]
            AppLanguage.ID -> idDict[key]
            AppLanguage.UR -> urDict[key]
            AppLanguage.SW -> swDict[key]
            AppLanguage.RU -> ruDict[key]
            AppLanguage.ZH -> zhDict[key]
            AppLanguage.DE -> deDict[key]
            AppLanguage.IT -> itDict[key]
            else -> sharedMultiLangKeys[key]?.get("en") ?: sharedMultiLangKeys[key]?.get("ar")
        }
    }

    fun hasKey(key: String): Boolean {
        return sharedMultiLangKeys.containsKey(key) ||
            trDict.containsKey(key) ||
            idDict.containsKey(key) ||
            urDict.containsKey(key) ||
            swDict.containsKey(key) ||
            ruDict.containsKey(key) ||
            zhDict.containsKey(key) ||
            deDict.containsKey(key) ||
            itDict.containsKey(key)
    }

    fun localizeMarketPost(post: MarketPostModel, lang: AppLanguage): MarketPostModel {
        val curr = Translations.tr("currency", lang)
        val qShort = Translations.tr("quintal_short", lang)
        val kgShort = Translations.tr("kg_short", lang)
        val chickUnit = Translations.tr("market_unit_per_chick", lang)
        return when (post.id) {
            "post_1" -> post.copy(
                title = Translations.tr("market_post_1_title", lang),
                description = Translations.tr("market_post_1_desc", lang),
                priceUnit = "$curr / $qShort",
                publisherName = Translations.tr("market_post_1_pub", lang),
                publisherLocation = Translations.tr("market_post_1_loc", lang),
                imageCaption = Translations.tr("market_post_1_cap", lang)
            )
            "post_2" -> post.copy(
                title = Translations.tr("market_post_2_title", lang),
                description = Translations.tr("market_post_2_desc", lang),
                priceUnit = "$curr / $kgShort",
                publisherName = Translations.tr("market_post_2_pub", lang),
                publisherLocation = Translations.tr("market_post_2_loc", lang),
                imageCaption = Translations.tr("market_post_2_cap", lang)
            )
            "post_3" -> post.copy(
                title = Translations.tr("market_post_3_title", lang),
                description = Translations.tr("market_post_3_desc", lang),
                priceUnit = "$curr / $chickUnit",
                publisherName = Translations.tr("market_post_3_pub", lang),
                publisherLocation = Translations.tr("market_post_3_loc", lang),
                imageCaption = Translations.tr("market_post_3_cap", lang)
            )
            else -> post.copy(
                priceUnit = if (post.priceUnit == "دج" || post.priceUnit == "DZD" || post.priceUnit == "USD") curr else post.priceUnit
            )
        }
    }

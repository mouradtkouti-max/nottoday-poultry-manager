/**
 * Parses an Agritech QR invitation string into [QrFarmInviteData].
 * Expected format generated by TeamQrInviteBottomSheet:
 * `AGRITECH_JOIN|farmId=farm_1|role=WORKER` or `AGRITECH_JOIN|farmId=farm_1|role=VETERINARIAN`
 */
fun parseAgritechQrInvite(rawValue: String, fallbackRole: AppRole = AppRole.WORKER): QrFarmInviteData? {
    val trimmed = rawValue.trim()
    if (trimmed.isEmpty()) return null

    if (trimmed.startsWith("AGRITECH_JOIN", ignoreCase = true) || trimmed.contains("farmId=", ignoreCase = true)) {
        val parts = trimmed.split("|", ";", "&")
        var extractedFarmId = "farm_1"
        var extractedRole = fallbackRole

        for (part in parts) {
            val kv = part.split("=")
            if (kv.size == 2) {
                val key = kv[0].trim().lowercase()
                val value = kv[1].trim()
                when (key) {
                    "farmid", "farm_id", "farm" -> if (value.isNotEmpty()) extractedFarmId = value
                    "role" -> {
                        extractedRole = when {
                            value.equals("VETERINARIAN", ignoreCase = true) ||
                                value.equals("VET", ignoreCase = true) -> AppRole.VETERINARIAN
                            value.equals("WORKER", ignoreCase = true) -> AppRole.WORKER
                            value.equals("OWNER", ignoreCase = true) -> AppRole.OWNER
                            else -> fallbackRole
                        }
                    }
                }
            }
        }
        return QrFarmInviteData(
            farmId = extractedFarmId,
            role = extractedRole,
            rawPayload = trimmed
        )
    }

    // Fallback if QR encodes a direct farmId (e.g., "farm_1")
    return QrFarmInviteData(
        farmId = if (trimmed.startsWith("farm_")) trimmed else "farm_1",
        role = fallbackRole,
        rawPayload = trimmed
    )
}

data class QrPersonalContactData(
    val name: String,
    val roleLabel: String,
    val phone: String,
    val rawPayload: String
)

fun parsePersonalContactQr(rawValue: String): QrPersonalContactData? {
    val trimmed = rawValue.trim()
    if (!trimmed.startsWith("MYBUSINESS_CONTACT", ignoreCase = true) && !trimmed.contains("phone=", ignoreCase = true)) {
        return null
    }
    var name = "شريك مزرعة"
    var role = "مربي / شريك"
    var phone = "+213 550 00 00 00"
    val parts = trimmed.split("|", ";", "&")
    for (part in parts) {
        val kv = part.split("=", limit = 2)
        if (kv.size == 2) {
            val k = kv[0].trim().lowercase()
            val v = kv[1].trim()
            when (k) {
                "name" -> if (v.isNotEmpty()) name = v
                "role" -> if (v.isNotEmpty()) role = v
                "phone", "tel" -> if (v.isNotEmpty()) phone = v
            }
        }
    }
    return QrPersonalContactData(
        name = name,
        roleLabel = role,
        phone = phone,
        rawPayload = trimmed
    )
}


/**
 * Real-time CameraX + Google ML Kit Barcode Scanner composable with graceful
 * runtime `Manifest.permission.CAMERA` handling.
 */
@OptIn(ExperimentalGetImage::class)
@Composable
fun RealQrCameraScannerView(
    selectedRoleFallback: AppRole,
    onQrCodeScanned: (QrFarmInviteData) -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current

    var hasCameraPermission by remember {
        mutableStateOf(
            ContextCompat.checkSelfPermission(
                context,
                Manifest.permission.CAMERA
            ) == PackageManager.PERMISSION_GRANTED
        )
    }
    var permissionDeniedOnce by remember { mutableStateOf(false) }
    var lastScannedRaw by remember { mutableStateOf<String?>(null) }

    val permissionLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.RequestPermission()
    ) { isGranted ->
        hasCameraPermission = isGranted
        if (!isGranted) {
            permissionDeniedOnce = true
        }
    }

    LaunchedEffect(Unit) {
        if (!hasCameraPermission) {
            permissionLauncher.launch(Manifest.permission.CAMERA)
        }
    }

    Surface(
        shape = RoundedCornerShape(22.dp),
        color = Color(0xFF0F172A),
        border = BorderStroke(2.dp, TextForestGreen),
        modifier = modifier
            .fillMaxWidth()
            .height(230.dp)
            .testTag("qr_camera_scanner_container")
    ) {
        if (hasCameraPermission) {
            Box(modifier = Modifier.fillMaxSize()) {
                val cameraExecutor = remember { Executors.newSingleThreadExecutor() }
                val barcodeScanner = remember {
                    val options = BarcodeScannerOptions.Builder()
                        .setBarcodeFormats(Barcode.FORMAT_QR_CODE)
                        .build()
                    BarcodeScanning.getClient(options)
                }

                DisposableEffect(Unit) {
                    onDispose {
                        try {
                            barcodeScanner.close()
                            cameraExecutor.shutdown()
                        } catch (_: Exception) {}
                    }
                }

                AndroidView(
                    modifier = Modifier
                        .fillMaxSize()
                        .clip(RoundedCornerShape(22.dp))
                        .testTag("qr_camera_preview_view"),
                    factory = { ctx ->
                        val previewView = PreviewView(ctx).apply {
                            implementationMode = PreviewView.ImplementationMode.COMPATIBLE
                            scaleType = PreviewView.ScaleType.FILL_CENTER
                        }
                        val cameraProviderFuture = ProcessCameraProvider.getInstance(ctx)
                        cameraProviderFuture.addListener({
                            try {
                                val cameraProvider = cameraProviderFuture.get()
                                val preview = Preview.Builder().build().also {
                                    it.setSurfaceProvider(previewView.surfaceProvider)
                                }
                                val imageAnalysis = ImageAnalysis.Builder()
                                    .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                                    .build()

                                imageAnalysis.setAnalyzer(cameraExecutor) { imageProxy ->
                                    val mediaImage = imageProxy.image
                                    if (mediaImage != null && lastScannedRaw == null) {
                                        val inputImage = InputImage.fromMediaImage(
                                            mediaImage,
                                            imageProxy.imageInfo.rotationDegrees
                                        )
                                        barcodeScanner.process(inputImage)
                                            .addOnSuccessListener { barcodes ->
                                                for (barcode in barcodes) {
                                                    val raw = barcode.rawValue
                                                    if (!raw.isNullOrBlank() && lastScannedRaw == null) {
                                                        val parsed = parseAgritechQrInvite(raw, selectedRoleFallback)
                                                        if (parsed != null) {
                                                            lastScannedRaw = raw
                                                            onQrCodeScanned(parsed)
                                                            break
                                                        }
                                                    }
                                                }
                                            }
                                            .addOnFailureListener { e ->
                                                Log.w("QrCameraScanner", "ML Kit QR scan error", e)
                                            }
                                            .addOnCompleteListener {
                                                imageProxy.close()
                                            }
                                    } else {
                                        imageProxy.close()
                                    }
                                }

                                cameraProvider.unbindAll()
                                cameraProvider.bindToLifecycle(
                                    lifecycleOwner,
                                    CameraSelector.DEFAULT_BACK_CAMERA,
                                    preview,
                                    imageAnalysis
                                )
                            } catch (e: Exception) {
                                Log.w("QrCameraScanner", "CameraX bind failed", e)
                            }
                        }, ContextCompat.getMainExecutor(ctx))
                        previewView
                    }
                )

                // Viewfinder Reticle Overlay
                Box(
                    modifier = Modifier.fillMaxSize(),
                    contentAlignment = Alignment.Center
                ) {
                    Surface(
                        shape = RoundedCornerShape(18.dp),
                        color = Color.Transparent,
                        border = BorderStroke(2.5.dp, Color(0xFF4ADE80)),
                        modifier = Modifier.size(150.dp)
                    ) {}
                }

                // Bottom Live Status Pill
                Surface(
                    shape = RoundedCornerShape(50),
                    color = Color(0xCC0F172A),
                    border = BorderStroke(1.dp, Color(0xFF4ADE80).copy(alpha = 0.6f)),
                    modifier = Modifier
                        .align(Alignment.BottomCenter)
                        .padding(bottom = 10.dp)
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 12.dp, vertical = 5.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        Icon(
                            imageVector = if (lastScannedRaw != null) Icons.Default.CheckCircle else Icons.Default.QrCodeScanner,
                            contentDescription = null,
                            tint = Color(0xFF4ADE80),
                            modifier = Modifier.size(15.dp)
                        )
                        Text(
                            text = if (lastScannedRaw != null) {
                                "تم التقاط الرمز بنجاح ✓"
                            } else {
                                "ماسح الكاميرا نشط (ML Kit QR)..."
                            },
                            color = Color.White,
                            fontSize = 11.sp,
                            fontWeight = FontWeight.Bold
                        )
                    }
                }
            }
        } else {
            // Graceful Camera Permission Request State (Ice Blue + Forest Green)
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .background(Color(0xFFE8F4FD))
                    .padding(18.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
                verticalArrangement = Arrangement.Center
            ) {
                Surface(
                    shape = CircleShape,
                    color = LightGreenContainer,
                    modifier = Modifier.size(50.dp)
                ) {
                    Box(contentAlignment = Alignment.Center) {
                        Icon(
                            Icons.Default.CameraAlt,
                            contentDescription = "Camera Permission",
                            tint = TextForestGreen,
                            modifier = Modifier.size(26.dp)
                        )
                    }
                }
                Spacer(modifier = Modifier.height(10.dp))
                Text(
                    text = if (permissionDeniedOnce) {
                        "يلزم منح صلاحية الكاميرا لمسح رمز QR الخاص بالعنبر"
                    } else {
                        "يرجى السماح بتشغيل الكاميرا لمسح رمز دعوة الفريق (QR)"
                    },
                    fontSize = 12.5.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextForestGreen,
                    textAlign = TextAlign.Center
                )
                Spacer(modifier = Modifier.height(10.dp))
                Button(
                    onClick = { permissionLauncher.launch(Manifest.permission.CAMERA) },
                    shape = RoundedCornerShape(12.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = TextForestGreen),
                    modifier = Modifier.testTag("btn_request_camera_permission")
                ) {
                    Icon(
                        Icons.Default.CameraAlt,
                        contentDescription = null,
                        tint = Color.White,
                        modifier = Modifier.size(16.dp)
                    )
                    Spacer(modifier = Modifier.width(6.dp))
                    Text(
                        "تفعيل الكاميرا للمسح 📷",
                        fontSize = 12.5.sp,
                        fontWeight = FontWeight.Bold,
                        color = Color.White
                    )
                }
            }
        }
    }
}
